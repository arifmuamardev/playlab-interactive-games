import {test,expect} from '@playwright/test';

test('Survey starter rehearsal preserves a scored live match and synchronizes its own projector',async({context})=>{
  const live=await context.newPage();
  await live.goto('?game=survey');
  await live.locator('.reveal-button').first().click();
  await live.locator('.award-btn--0').click();
  await expect(live.locator('.team-editor--0 strong')).toHaveText('34');
  const snapshot=await live.evaluate(()=>localStorage.getItem('playlab-survey-showdown-v2'));
  const setup=await context.newPage();
  await setup.goto('?page=dashboard&tab=setup&format=survey');
  await setup.getByRole('button',{name:'Continue'}).click();
  await setup.getByRole('radio',{name:/Ready-to-use classroom/i}).check();
  await setup.locator('#setup-template').selectOption('survey-community-v1');
  await setup.getByRole('button',{name:'Continue'}).click();
  await setup.getByLabel('Team 1').fill('Event A');
  await setup.getByLabel('Team 2').fill('Event B');
  await setup.getByRole('button',{name:'Continue'}).click();
  await expect(setup.getByText(/Community Game Night · 8 questions/)).toBeVisible();
  const opened=setup.waitForEvent('popup');
  await setup.getByRole('button',{name:/Practice without affecting live game/i}).click();
  const practice=await opened;
  await expect(practice).toHaveURL(/game=survey&mode=rehearsal/);
  await expect(practice.getByText('Practice mode',{exact:true})).toBeVisible();
  await expect(practice.locator('.playlab-pregame-welcome')).toBeVisible();
  await practice.getByRole('button',{name:/Next: Meet the teams/}).click();
  await practice.getByRole('button',{name:/Next: Game rules/}).click();
  await practice.getByRole('button',{name:'Start Game'}).click();
  await expect(practice.locator('.team-editor--0 input')).toHaveValue('Event A');
  await expect(practice.locator('.reveal-button')).toHaveCount(5);
  await expect(practice.locator('.stage-question h1')).toContainText('community gathering');
  const openedProjector=practice.waitForEvent('popup');
  await practice.getByRole('button',{name:/Open projector view/}).click();
  const projector=await openedProjector;
  await expect(projector).toHaveURL(/mode=rehearsal/);
  await practice.locator('.reveal-button').first().click();
  await practice.locator('.award-btn--0').click();
  await expect(projector.locator('.team-score--0 .team-number')).toHaveText('36');
  expect(await live.evaluate(()=>localStorage.getItem('playlab-survey-showdown-v2'))).toBe(snapshot);
  await live.reload();
  await expect(live.locator('.team-editor--0 strong')).toHaveText('34');
  await expect(setup.getByText('Review your new match')).toBeVisible();
});

test('Quickfire event starter rehearses without creating a live game',async({context})=>{
  const setup=await context.newPage();
  await setup.goto('?page=dashboard&tab=setup&format=quickfire');
  await setup.getByRole('button',{name:'Continue'}).click();
  await setup.getByRole('radio',{name:/Ready-to-use classroom/i}).check();
  await setup.locator('#setup-template').selectOption('quickfire-general-v1');
  await setup.getByRole('button',{name:'Continue'}).click();
  await setup.getByLabel('Team 1').fill('Red');
  await setup.getByLabel('Team 2').fill('Blue');
  await setup.getByRole('button',{name:'Continue'}).click();
  const opened=setup.waitForEvent('popup');
  await setup.getByRole('button',{name:/Practice without affecting live game/i}).click();
  const practice=await opened;
  await expect(practice).toHaveURL(/mode=rehearsal/);
  await expect(practice.locator('.playlab-pregame-welcome')).toBeVisible();
  await practice.getByRole('button',{name:/Next: Meet the teams/}).click();
  await practice.getByRole('button',{name:/Next: Game rules/}).click();
  await practice.getByRole('button',{name:'Start Game'}).click();
  await expect(practice.locator('.quick-question')).toContainText('How many minutes');
  await practice.getByRole('button',{name:'Reveal correct answer'}).click();
  await expect(practice.locator('.quick-option.correct').first()).toContainText('60');
  await practice.getByRole('button',{name:'Add ten points to team 1'}).click();
  await expect(practice.locator('.quick-team-editor').first().locator('strong')).toHaveText('10');
  expect(await setup.evaluate(()=>localStorage.getItem('playlab-quickfire-state-v1'))).toBeNull();
  const state=await setup.evaluate(()=>JSON.parse(localStorage.getItem('playlab-quickfire-rehearsal-v1')));
  expect(state.scores[0]).toBe(10);
  await expect(setup.getByText('Review your new match')).toBeVisible();
});
